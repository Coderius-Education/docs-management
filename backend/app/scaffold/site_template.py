def scaffold_files(
    slug: str,
    title: str,
    tagline: str,
    description: str,
    *,
    subject: str = "informatica",
) -> dict[str, bytes]:
    """Pad (in het docs-repo) -> inhoud (bytes) voor een minimale nieuwe site.

    Het adres (<vak-domein>/<path>/) volgt uit de registry-entry in sites.js.
    """
    base = site_dir_for(subject, slug)
    files = {
        f"{base}/package.json": _package_json(slug),
        f"{base}/docusaurus.config.ts": _docusaurus_config(slug, title, tagline, description),
        f"{base}/sidebars.ts": _SIDEBARS_TS,
        f"{base}/tsconfig.json": _TSCONFIG_JSON,
        f"{base}/src/pages/index.tsx": _INDEX_TSX,
        f"{base}/src/pages/docenten.mdx": _docenten_mdx(slug, title),
        f"{base}/src/content/homepage.mdx": _HOMEPAGE_MDX,
        f"{base}/site-settings.json": json.dumps(_MANAGED_SETTINGS, indent=2) + "\n",
        f"{base}/authoring-capabilities.json": json.dumps(_CAPABILITIES, indent=2) + "\n",
        f"{base}/src/css/managed-theme.css": "/* Generated from site-settings.json. */\n",
        f"{base}/docs/intro.md": _intro_md(title),
    }
    return {p: content.encode("utf-8") for p, content in files.items()}


# --- registers ---------------------------------------------------------------


def _dump_registry(registry: dict) -> str:
    """sites.json in de vaste stijl: één regel per vak en per site (diff-vriendelijk)."""

    def line(item: dict) -> str:
        # `{ "slug": … }`, met spaties binnen de accolades: de opmaak van het bestand.
        return "{ " + json.dumps(item, ensure_ascii=False)[1:-1] + " }"

    def block(items: list[dict]) -> str:
        return ",\n".join(f"    {line(item)}" for item in items)

    return (
        "{\n"
        f'  "apex": {json.dumps(registry["apex"])},\n'
        f'  "subjects": [\n{block(registry["subjects"])}\n  ],\n'
        f'  "sites": [\n{block(registry["sites"])}\n  ]\n'
        "}\n"
    )


def add_subject_to_registry(sites_json: str, subject: str, domain: str, display_name: str) -> str:
    registry = json.loads(sites_json)
    if any(s["slug"] == subject for s in registry["subjects"]):
        raise ValueError(f"Vak '{subject}' staat al in sites.json")
    registry["subjects"].append({"slug": subject, "domain": domain, "display_name": display_name})
    return _dump_registry(registry)


def add_site_to_registry(
    sites_json: str, slug: str, subject: str, path: str, display_name: str
) -> str:
    """Voegt een site toe aan sites.json, vóór `home` (die blijft de laatste)."""
    registry = json.loads(sites_json)
    if any(s["slug"] == slug for s in registry["sites"]):
        raise ValueError(f"Site '{slug}' staat al in sites.json")
    if not any(s["slug"] == subject for s in registry["subjects"]):
        raise ValueError(f"Onbekend vak '{subject}' in sites.json")
    if any(s.get("subject") == subject and s.get("path") == path for s in registry["sites"]):
        raise ValueError(f"Pad '/{path}/' is al in gebruik binnen '{subject}'")
    entry = {
        "slug": slug,
        "subject": subject,
        "path": path,
        "display_name": display_name,
        "legacy_domains": [],
    }
    sites = registry["sites"]
    home = next((i for i, s in enumerate(sites) if s["slug"] == "home"), len(sites))
    sites.insert(home, entry)
    return _dump_registry(registry)


def _js_str(value: str) -> str:
    """JS-stringliteral met enkele quotes (huisstijl van sites.js)."""
    escaped = value.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n")
    return f"'{escaped}'"


def _append_to_js_array(
    source: str,
    opening: str,
    closing: str,
    name: str,
    entry: str,
    file: str = "packages/shared/sites.js",
) -> str:
    """Voegt `entry` toe als laatste element van het array dat met `opening` begint."""
    start = source.find(opening)
    if start == -1:
        raise ValueError(
            f"Kon '{opening.strip()}' niet vinden in {file}; is de opbouw van {name} veranderd?"
        )
    end = source.find(closing, start + len(opening) - 1)
    if end == -1:
        raise ValueError(f"Kon het einde van {name} ('{closing.strip()}') niet vinden in {file}")
    return source[:end] + "\n" + entry.rstrip("\n") + source[end:]


def add_subject_to_sites_js(sites_js: str, subject: str, domain: str, display_name: str) -> str:
    """Nieuw vak achteraan in `const SUBJECTS = [ … ];` ({ id, label, url })."""
    if re.search(rf"id: '{re.escape(subject)}'", sites_js):
        raise ValueError(f"Vak '{subject}' staat al in sites.js")
    entry = (
        f"  {{ id: {_js_str(subject)}, label: {_js_str(display_name)}, "
        f"url: {_js_str(f'https://{domain}')} }},"
    )
    return _append_to_js_array(sites_js, "const SUBJECTS = [\n", "\n];", "SUBJECTS", entry)


def add_site_to_sites_js(
    sites_js: str, slug: str, subject: str, path: str, label: str, description: str
) -> str:
    """Nieuwe cursus achteraan in `const SITES = defineSites([ … ]);`.

    `url` schrijven we niet: defineSites leidt die af uit vak + pad. `legacyUrl`
    is alleen voor oude subdomeinen. De leerlijn-volgorde zet een docent later goed.
    """
    if re.search(rf"id: '{re.escape(slug)}'", sites_js):
        raise ValueError(f"Site '{slug}' staat al in sites.js")
    entry = (
        "  {\n"
        f"    id: {_js_str(slug)},\n"
        f"    label: {_js_str(label)},\n"
        f"    subject: {_js_str(subject)},\n"
        f"    path: {_js_str(path)},\n"
        f"    description: {_js_str(description)},\n"
        "    requires: [],\n"
        "  },"
    )
    return _append_to_js_array(sites_js, "const SITES = defineSites([\n", "\n]);", "SITES", entry)


# --- huisstijl en homepage ----------------------------------------------------

HUISSTIJL_JS = "packages/shared/huisstijl/index.js"
CURRICULUM_TS = "sites/home/src/lib/Curriculum.ts"

# Een glyph moet in packages/shared/huisstijl/merk.js bestaan; een eigen teken
# tekent een mens. Tot dan draagt de cursus de cursor van Coderius.
DEFAULT_GLYPH = "cursor"


def free_tint(huisstijl_js: str) -> int:
    """Het midden van het grootste gat tussen de tinten op de kleurcirkel, zodat
    een nieuwe cursus zo ver mogelijk van de andere kleuren af ligt."""
    tints = sorted({int(t) % 360 for t in re.findall(r"\btint: (\d+)", huisstijl_js)})
    if not tints:
        return 0
    best_start, best_gap = tints[-1], tints[0] + 360 - tints[-1]
    for a, b in zip(tints, tints[1:], strict=False):
        if b - a > best_gap:
            best_start, best_gap = a, b - a
    return (best_start + best_gap // 2) % 360


def add_course_to_huisstijl(huisstijl_js: str, slug: str, label: str) -> str:
    """Nieuwe cursus achteraan in `const CURSUSSEN = [ … ];` (huisstijl.test.ts eist
    een merk per cursus; genereer-huisstijl.mjs maakt de bestanden)."""
    if re.search(rf"id: '{re.escape(slug)}'", huisstijl_js):
        raise ValueError(f"Cursus '{slug}' staat al in {HUISSTIJL_JS}")
    entry = (
        f"  {{ id: {_js_str(slug)}, label: {_js_str(label)}, "
        f"tint: {free_tint(huisstijl_js)}, glyph: {_js_str(DEFAULT_GLYPH)} }},"
    )
    return _append_to_js_array(
        huisstijl_js, "const CURSUSSEN = [\n", "\n];", "CURSUSSEN", entry, HUISSTIJL_JS
    )


_THEMAS_OPENING = "export const THEMAS_PER_VAK = {\n"


def subject_themes(curriculum_ts: str, subject: str) -> list[str]:
    """De thema's van een vak uit THEMAS_PER_VAK in Curriculum.ts (leeg als het
    vak er niet staat)."""
    start = curriculum_ts.find(_THEMAS_OPENING)
    end = curriculum_ts.find("\n} as const;", start)
    if start == -1 or end == -1:
        raise ValueError(f"Kon THEMAS_PER_VAK niet vinden in {CURRICULUM_TS}")
    block = curriculum_ts[start:end]
    match = re.search(rf"^  {re.escape(subject)}: \[(.*?)\],$", block, re.M)
    return re.findall(r"'([^']*)'", match.group(1)) if match else []


def add_subject_themes(curriculum_ts: str, subject: str, theme: str) -> str:
    """Een nieuw vak met één thema in THEMAS_PER_VAK (Curriculum.test.ts eist dat
    elke cursus onder een thema van zijn vak valt)."""
    if subject_themes(curriculum_ts, subject):
        raise ValueError(f"Vak '{subject}' heeft al thema's in {CURRICULUM_TS}")
    entry = f"  {subject}: [{_js_str(theme)}],"
    return _append_to_js_array(
        curriculum_ts, _THEMAS_OPENING, "\n} as const;", "THEMAS_PER_VAK", entry, CURRICULUM_TS
    )


def add_course_to_curriculum(curriculum_ts: str, slug: str, theme: str) -> str:
    """Een kaart op de homepage. Naam, omschrijving en adres komen uit de registry;
    hier staat alleen wat de registry niet weet. Het thema staat letterlijk in
    projectTypes (themasVan pakt een thema van het eigen vak daaruit op). Niveau,
    klas en volgorde zijn een begin; de docent zet ze later goed."""
    if re.search(rf"^    id: '{re.escape(slug)}',$", curriculum_ts, re.M):
        raise ValueError(f"Cursus '{slug}' staat al in {CURRICULUM_TS}")
    entry = (
        "  {\n"
        f"    id: {_js_str(slug)},\n"
        "    labels: [],\n"
        "    programmingLanguages: [],\n"
        f"    projectTypes: [{_js_str(theme)}],\n"
        "    operatingSystems: ['Windows', 'Linux', 'macOS', 'ChromeOS'],\n"
        "    level: 'Beginner',\n"
        "    klas: '4 en 5+',\n"
        "    order: {\n"
        "      vwo: 1,\n"
        "      havo: 1,\n"
        "    },\n"
        "  },"
    )
    return _append_to_js_array(
        curriculum_ts,
        "const entries: CurriculumEntry[] = [\n",
        "\n];",
        "entries",
        entry,
        CURRICULUM_TS,
    )
